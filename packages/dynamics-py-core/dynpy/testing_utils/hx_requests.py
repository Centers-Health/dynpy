from django.contrib.messages.storage.fallback import FallbackStorage
from django.http import HttpResponse
from django.test import RequestFactory
from django.views import View
from hx_requests.hx_requests import BaseHxRequest
from hx_requests.utils import serialize, serialize_kwargs


def add_middleware_to_request(request):
    request.session = "session"
    messages = FallbackStorage(request)
    request._messages = messages

    return request


def _create_test_request(
    hx_request, request_attrs=None, hx_kwargs=None, get_params=None, method="GET", post_data=None
):
    hx_kwargs = hx_kwargs or {}
    request_attrs = request_attrs or {}
    get_params = get_params or {}

    def set_request_attrs(request):
        META = request_attrs.pop("META", {})
        for attr, value in request_attrs.items():
            setattr(request, attr, value)
        request.META["HTTP_HX_REQUEST"] = True
        request.META.update(META)
        return request

    # Used even on POST to set kwargs to GET params
    hx_object = hx_kwargs.pop("object", None)
    hx_kwargs = serialize_kwargs(**hx_kwargs)
    if hx_object:
        hx_kwargs["object"] = serialize(hx_object)
    hx_kwargs["hx_request_name"] = hx_request.name
    hx_kwargs.update(get_params)
    request = RequestFactory().get("/", data=hx_kwargs)

    if method == "POST":
        request = RequestFactory().post(f"/?{request.META['QUERY_STRING']}", data=post_data or {})

    request = set_request_attrs(request)
    add_middleware_to_request(request)
    return request


def hx_get(
    hx_request: BaseHxRequest,
    view: View,
    request_attrs: dict | None = None,
    view_kwargs: dict | None = None,
    hx_kwargs: dict | None = None,
    get_params: dict | None = None,
):
    """
    Used to test a BaseHxRequest with a GET request through a view.
    Parameters:
    - hx_request (BaseHxRequest): The HXRequest object representing the request
    - view (View): The view object to process the request
    - view_kwargs (dict, optional): A dict of keyword arguments to be passed to the view
    - request_attrs (dict, optional): Additional attributes to set on the request object
    - hx_kwargs (dict, optional): Additional keyword arguments for the request
    - get_params (dict, optional): Additional GET parameters for the request (Not Serialized)

    Returns:
    - HttpResponse: The response generated by the HXRequest
    """
    request = _create_test_request(hx_request, request_attrs, hx_kwargs, get_params=get_params)
    view_kwargs = view_kwargs or {}
    return view.as_view()(request, **view_kwargs)


def hx_post(
    hx_request: BaseHxRequest,
    view: View,
    request_attrs: dict | None = None,
    view_kwargs: dict | None = None,
    hx_kwargs: dict | None = None,
    get_params: dict | None = None,
    post_data: dict | None = None,
) -> HttpResponse:
    """
    Used to test a BaseHxRequest with a POST request through a view.
    Parameters:
    - hx_request (BaseHxRequest): The HXRequest object representing the request
    - view (View): The view object to process the request
    - view_kwargs (dict, optional): A dict of keyword arguments to be passed to the view
    - request_attrs (dict, optional): Additional attributes to set on the request object
    - hx_kwargs (dict, optional): Additional keyword arguments for the request
    - post_data (dict, optional): The data to be sent in the POST request

    Returns:
    - HttpResponse: The response generated by the HXRequest
    """
    request = _create_test_request(
        hx_request,
        request_attrs=request_attrs,
        hx_kwargs=hx_kwargs,
        method="POST",
        get_params=get_params,
        post_data=post_data,
    )
    view_kwargs = view_kwargs or {}
    return view.as_view()(request, **view_kwargs)
